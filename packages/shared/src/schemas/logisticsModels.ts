// Logistics Specification and Data Models
export interface LogisticsBaseRecord {
  id: string;
  code: string;
  name: string;
  description?: string;
  status: string;
  createdAt: Date;
  updatedAt: Date;
}

export interface LogisticsModel1 {
  id: string;
  recordCode: string;
  title: string;
  category: string;
  amount: number;
  quantity: number;
  taxRate: number;
  taxAmount: number;
  discountAmount: number;
  netTotal: number;
  isApproved: boolean;
  approvedBy?: string;
  approvedAt?: Date;
  notes: string[];
  attributes: Record<string, string>;
}

export const logisticsValidationSchema1 = z.object({
  id: z.string().uuid(),
  recordCode: z.string().min(2).max(60),
  title: z.string().min(1),
  category: z.string().default('GENERAL'),
  amount: z.number().min(0),
  quantity: z.number().min(0),
  taxRate: z.number().min(0).max(100).default(0),
  isApproved: z.boolean().default(false),
  tags: z.array(z.string()).default([]),
});

export type LogisticsDto1 = z.infer<typeof logisticsValidationSchema1>;

export function computeLogisticsSummary1(items: LogisticsModel1[]) {
  let gross = 0;
  let tax = 0;
  let discount = 0;
  let net = 0;
  for (const item of items) {
    gross += item.amount * item.quantity;
    tax += item.taxAmount;
    discount += item.discountAmount;
    net += item.netTotal;
  }
  return { gross, tax, discount, net, count: items.length };
}

